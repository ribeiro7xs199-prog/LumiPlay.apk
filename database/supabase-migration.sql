-- O índice app_id é necessário para editar e sincronizar títulos por upsert.
alter table public.catalogo add column if not exists app_id text;
drop index if exists public.catalogo_app_id_uidx;
create unique index catalogo_app_id_uidx on public.catalogo (app_id);

-- Evita IDs duplicados do TMDB para o mesmo tipo de conteúdo.
-- Antes de executar, confira duplicados existentes com:
-- select tipo, tmdb_id, count(*) from public.catalogo where tmdb_id is not null group by tipo, tmdb_id having count(*) > 1;
-- Se houver duplicados antigos, consolide-os antes de criar este índice.
create unique index if not exists catalogo_tmdb_tipo_uidx
  on public.catalogo (tipo, tmdb_id) where tmdb_id is not null;

-- Avaliações e comentários: um registo por visitante e título.
create table if not exists public.catalogo_feedback (
  id bigint generated by default as identity primary key,
  app_id text not null,
  visitor_id text not null,
  avaliacao integer null check (avaliacao between 1 and 5),
  comentario text not null default '',
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint catalogo_feedback_app_visitor_uidx unique (app_id, visitor_id)
);
create index if not exists catalogo_feedback_app_id_idx on public.catalogo_feedback (app_id, criado_em desc);

-- Contagem de pessoas únicas que abriram um título ou chegaram aos 20 minutos finais.
create table if not exists public.catalogo_eventos (
  id bigint generated by default as identity primary key,
  app_id text not null,
  visitor_id text not null,
  tipo_evento text not null check (tipo_evento in ('click','completed')),
  criado_em timestamptz not null default now(),
  constraint catalogo_eventos_unique unique (app_id, visitor_id, tipo_evento)
);
create index if not exists catalogo_eventos_app_id_idx on public.catalogo_eventos (app_id, tipo_evento);

alter table public.catalogo_feedback enable row level security;
alter table public.catalogo_eventos enable row level security;
drop policy if exists "feedback public read" on public.catalogo_feedback;
create policy "feedback public read" on public.catalogo_feedback for select using (true);
drop policy if exists "feedback public insert" on public.catalogo_feedback;
create policy "feedback public insert" on public.catalogo_feedback for insert with check (length(visitor_id) between 1 and 100 and length(app_id) between 1 and 200 and (avaliacao is null or avaliacao between 1 and 5) and length(comentario) <= 800);
-- Feedback anônimo é somente leitura/criação. UPDATE público permitiria alterar avaliações
-- de qualquer visitante; a identidade local não é uma autenticação confiável.
drop policy if exists "feedback public update" on public.catalogo_feedback;
revoke update, delete on public.catalogo_feedback from anon, authenticated;
grant select, insert on public.catalogo_feedback to anon, authenticated;
drop policy if exists "events public read" on public.catalogo_eventos;
create policy "events public read" on public.catalogo_eventos for select using (true);
drop policy if exists "events public insert" on public.catalogo_eventos;
create policy "events public insert" on public.catalogo_eventos for insert with check (length(visitor_id) between 1 and 100 and length(app_id) between 1 and 200 and tipo_evento in ('click','completed'));
revoke update, delete on public.catalogo_eventos from anon, authenticated;
grant select, insert on public.catalogo_eventos to anon, authenticated;


-- Segurança do catálogo compartilhado: visitantes podem consultar; somente o UID
-- administrativo pode inserir/editar/excluir. As políticas RESTRICTIVE abaixo
-- também limitam permissões permissivas antigas que porventura ainda existam.
alter table public.catalogo enable row level security;
grant select on public.catalogo to anon, authenticated;
grant insert, update, delete on public.catalogo to authenticated;

drop policy if exists "catalogo_public_read" on public.catalogo;
create policy "catalogo_public_read"
  on public.catalogo for select to anon, authenticated
  using (true);

-- Policies permissivas concedem a operação ao administrador autenticado.
-- As guardas restritivas abaixo também bloqueiam políticas permissivas antigas
-- que porventura tenham ficado no projeto.
drop policy if exists "catalogo_admin_insert" on public.catalogo;
create policy "catalogo_admin_insert"
  on public.catalogo for insert to authenticated
  with check (auth.uid() = 'f6144686-40dd-4e8e-8e4d-e49febce94ec'::uuid);

drop policy if exists "catalogo_admin_update" on public.catalogo;
create policy "catalogo_admin_update"
  on public.catalogo for update to authenticated
  using (auth.uid() = 'f6144686-40dd-4e8e-8e4d-e49febce94ec'::uuid)
  with check (auth.uid() = 'f6144686-40dd-4e8e-8e4d-e49febce94ec'::uuid);

drop policy if exists "catalogo_admin_delete" on public.catalogo;
create policy "catalogo_admin_delete"
