-- LumiPlay Etapa 13: denúncias privadas de comentários da comunidade.
-- Execute no SQL Editor do projeto Supabase correto antes de usar a ação Denunciar.
-- Faça backup antes de executar alterações de banco.

create table if not exists public.catalogo_denuncias_feedback (
  id bigint generated by default as identity primary key,
  feedback_id bigint not null references public.catalogo_feedback(id) on delete cascade,
  app_id text not null,
  reporter_visitor_id text not null,
  motivo text not null,
  criado_em timestamptz not null default now(),
  constraint catalogo_denuncias_feedback_unique unique (feedback_id, reporter_visitor_id),
  constraint catalogo_denuncias_feedback_motivo_len check (length(trim(motivo)) between 10 and 500)
);

create index if not exists catalogo_denuncias_feedback_created_idx
  on public.catalogo_denuncias_feedback (criado_em desc);

alter table public.catalogo_denuncias_feedback enable row level security;
revoke all on public.catalogo_denuncias_feedback from anon, authenticated;
grant insert on public.catalogo_denuncias_feedback to anon, authenticated;
grant usage, select on sequence public.catalogo_denuncias_feedback_id_seq to anon, authenticated;

drop policy if exists "feedback reports public insert" on public.catalogo_denuncias_feedback;
create policy "feedback reports public insert"
  on public.catalogo_denuncias_feedback for insert to anon, authenticated
  with check (
    feedback_id > 0
    and length(app_id) between 1 and 200
    and length(reporter_visitor_id) between 1 and 100
    and length(trim(motivo)) between 10 and 500
    and exists (
      select 1 from public.catalogo_feedback f
      where f.id = feedback_id and f.app_id = catalogo_denuncias_feedback.app_id
        and f.visitor_id <> catalogo_denuncias_feedback.reporter_visitor_id
    )
  );

-- Não existe política pública de SELECT, UPDATE ou DELETE para denúncias.
-- Revise-as por uma sessão administrativa confiável, nunca exponha dados de denúncia ao público.


-- Etapa 14: fila de moderação acessível apenas ao UID administrador configurado no app.
alter table public.catalogo_denuncias_feedback
  add column if not exists status text not null default 'pending',
  add column if not exists resolved_at timestamptz,
  add column if not exists resolved_by uuid;

alter table public.catalogo_denuncias_feedback
  drop constraint if exists catalogo_denuncias_feedback_status_check;
alter table public.catalogo_denuncias_feedback
  add constraint catalogo_denuncias_feedback_status_check check (status in ('pending','reviewed'));

-- A tabela de denúncias não ganha acesso público de leitura. Somente a sessão autenticada
-- com o UID administrador definido no app pode consultar/atualizar a fila.
grant select on public.catalogo_denuncias_feedback to authenticated;
grant update (status, resolved_at, resolved_by) on public.catalogo_denuncias_feedback to authenticated;
drop policy if exists "reports admin read" on public.catalogo_denuncias_feedback;
create policy "reports admin read" on public.catalogo_denuncias_feedback
  for select to authenticated using (auth.uid() = 'f6144686-40dd-4e8e-8e4d-e49febce94ec'::uuid);
drop policy if exists "reports admin update" on public.catalogo_denuncias_feedback;
create policy "reports admin update" on public.catalogo_denuncias_feedback
  for update to authenticated
  using (auth.uid() = 'f6144686-40dd-4e8e-8e4d-e49febce94ec'::uuid)
  with check (auth.uid() = 'f6144686-40dd-4e8e-8e4d-e49febce94ec'::uuid);

-- Remoção de comentário somente pela conta administradora. As denúncias relacionadas
-- são removidas por ON DELETE CASCADE. Visitantes continuam sem permissão de DELETE.
grant delete on public.catalogo_feedback to authenticated;
drop policy if exists "feedback admin delete" on public.catalogo_feedback;
create policy "feedback admin delete" on public.catalogo_feedback
  for delete to authenticated using (auth.uid() = 'f6144686-40dd-4e8e-8e4d-e49febce94ec'::uuid);

-- Etapa 15: trilha de auditoria para ações administrativas.
-- O histórico não guarda senhas nem tokens. Faça backup antes de aplicar.
create table if not exists public.lumiplay_admin_audit (
  id bigint generated by default as identity primary key,
  actor_uid uuid not null,
  action text not null check (action in ('report_reviewed','comment_removed','admin_login')),
  target_type text not null check (length(target_type) between 1 and 40),
  target_id text not null check (length(target_id) <= 200),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists lumiplay_admin_audit_created_idx
  on public.lumiplay_admin_audit (created_at desc);
alter table public.lumiplay_admin_audit enable row level security;
revoke all on public.lumiplay_admin_audit from anon, authenticated;
grant select, insert on public.lumiplay_admin_audit to authenticated;
grant usage, select on sequence public.lumiplay_admin_audit_id_seq to authenticated;
drop policy if exists "lumiplay audit admin read" on public.lumiplay_admin_audit;
create policy "lumiplay audit admin read" on public.lumiplay_admin_audit
  for select to authenticated using (auth.uid() = 'f6144686-40dd-4e8e-8e4d-e49febce94ec'::uuid);
drop policy if exists "lumiplay audit admin insert" on public.lumiplay_admin_audit;
create policy "lumiplay audit admin insert" on public.lumiplay_admin_audit
  for insert to authenticated with check (auth.uid() = 'f6144686-40dd-4e8e-8e4d-e49febce94ec'::uuid and actor_uid = auth.uid());
-- Não há política de UPDATE/DELETE: o histórico não pode ser alterado pelo cliente.
